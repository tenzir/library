"""Vendors a SOC Prime detection content snapshot into the package.

The snapshot is the `detection_content` directory of
https://github.com/socprime/detectflow-backend. Run from the package root:

    scripts/vendor.py /path/to/detectflow-backend/detection_content

The script writes `constants.tql` with the Sigma rules and Active Threats,
and one `operators/hos/<name>.tql` operator per High-Order Sigma (HoS) rule.
Name new HoS rules in `HOS_OPERATORS` below.
"""

import datetime
import json
import pathlib
import sys

import yaml

PACKAGE = pathlib.Path(__file__).resolve().parent.parent

# Operator names of the HoS rules, keyed by TDM ID.
HOS_OPERATORS = {
    "r0LqNjnpT21W": "kimsuky_diplomats",
    "Zk2Qr9RO5Dth": "remcos_purchase_order",
    "YAXTrTrvQXoi": "gamaredon",
    "gTSmKZquRCYV": "uac_0247",
    "p6ndiutIHfyH": "janaware",
    "jhP5r9lpFLqg": "node2shell",
    "Riwu9NconRzw": "php2shell",
    "UfhULfdvVPtu": "n8n_abuse",
    "JVLEu7LOwbcg": "dragon_boss",
    "knjkfvZHX16t": "windows_privesc_persistence",
}

HOS_TEMPLATE = """\
---
description: |
{description}
args:
  named:
    - name: timeframe
      type: duration
      default: {timeframe}
      description: The time span that a chain must fit into.
    - name: threshold
      type: float
      default: 0.6
      description: The share of stages a host must cover, between 0 and 1.
    - name: tolerance
      type: duration
      default: 1min
      description: How far findings of a host may arrive out of time order.
---

// Generated by scripts/vendor.py from the SOC Prime HoS rule {tdm_id}.
let $stages = {{
{stages}
}}
sigma rules=[{spread}].map(uid => socprime::$rules[uid])
socprime::hos::chain uid="{uid}",
  name={name},
  level="{level}",
  tags={tags},
  stages=$stages,
  timeframe=$timeframe,
  threshold=$threshold,
  tolerance=$tolerance
"""


def tql(value, indent=0):
    """Renders a Python value as a TQL literal."""
    pad = "  " * indent
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, datetime.datetime):
        return value.astimezone(datetime.UTC).isoformat().replace("+00:00", "Z")
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, list):
        if not value:
            return "[]"
        items = [f"{pad}  {tql(v, indent + 1)}," for v in value]
        return "[\n" + "\n".join(items) + f"\n{pad}]"
    if isinstance(value, dict):
        if not value:
            return "{}"
        items = [f"{pad}  {k}: {tql(v, indent + 1)}," for k, v in value.items()]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    raise TypeError(f"unsupported value: {value!r}")


def warn(message):
    print(f"warning: {message}", file=sys.stderr)
    return False


def duration(text):
    units = {"s": "s", "m": "min", "h": "h", "d": "d"}
    return text[:-1] + units[text[-1]]


def wrap(text, width=76):
    import textwrap

    paragraphs = [" ".join(p.split()) for p in text.strip().split("\n\n")]
    lines = []
    for paragraph in paragraphs:
        lines += textwrap.wrap(paragraph, width) + [""]
    return "\n".join(f"  {l}" if l else "" for l in lines[:-1])


def tags(values):
    text = json.dumps(values)
    if len(text) <= 70:
        return text
    return "[\n" + "".join(f"    {json.dumps(v)},\n" for v in values) + "  ]"


def hos_operator(tdm_id, rule, by_uid):
    stages = []
    spread = []
    for key, stage in rule["detection"].items():
        if not key.startswith("seq"):
            continue
        lines = [f"  {key}: ["]
        for uid in stage["ruleid|contains"]:
            if uid in by_uid:
                lines.append(f'    "{uid}", // {by_uid[uid]["name"]}')
            else:
                lines.append(f'    // "{uid}", // Missing from the snapshot.')
        lines.append("  ],")
        stages += lines
        spread.append(f"...$stages.{key}")
    description = "\n\n".join(
        [
            f'Detects the SOC Prime High-Order Sigma rule "{rule["title"]}".',
            rule.get("description") or "",
            f"The rule chains {len(spread)} stages of SOC Prime behavior rules "
            "by host. See `socprime::hos::chain` for the correlation and the "
            "resulting Detection Finding.",
        ]
    )
    return HOS_TEMPLATE.format(
        description=wrap(description),
        timeframe=duration(rule["detection"]["timeframe"]),
        tdm_id=tdm_id,
        stages="\n".join(stages),
        spread=", ".join(spread),
        uid=rule["id"],
        name=json.dumps(rule["title"], ensure_ascii=False),
        level=rule["level"],
        tags=tags(rule.get("tags") or []),
    )


def timestamp(text):
    return datetime.datetime.fromisoformat(text)


def load(directory):
    return [yaml.safe_load(f.read_text()) for f in sorted(directory.glob("*.yml"))]


def main(snapshot):
    snapshot = pathlib.Path(snapshot)
    version = (snapshot / "VERSION").read_text().strip()
    # Sigma rules, keyed by their TDM ID.
    rules = {}
    for item in load(snapshot / "rules"):
        body = item["body"].strip() + "\n"
        assert '"#' not in body, f"rule {item['id']} breaks the raw string"
        rule = yaml.safe_load(body)
        rules[item["id"]] = {"uid": rule["id"], "name": rule["title"], "body": body}
    by_uid = {r["uid"]: r for r in rules.values()}
    # High-Order Sigma rules, keyed by their TDM ID.
    hos = {}
    hos_rules = {}
    for item in load(snapshot / "hos"):
        rule = yaml.safe_load(item["body"])
        for key, stage in rule["detection"].items():
            if key.startswith("seq"):
                for uid in stage["ruleid|contains"]:
                    if uid not in by_uid:
                        warn(f"HoS {rule['id']} references missing rule {uid}")
        hos[item["id"]] = {"uid": rule["id"], "name": rule["title"]}
        hos_rules[item["id"]] = [
            uid
            for key, stage in rule["detection"].items()
            if key.startswith("seq")
            for uid in stage["ruleid|contains"]
            if uid in by_uid
        ]
        name = HOS_OPERATORS[item["id"]]
        (PACKAGE / "operators" / "hos" / f"{name}.tql").write_text(
            hos_operator(item["id"], rule, by_uid)
        )
    # Active Threats with resolved rule references.
    threats = []
    for item in load(snapshot / "active_threats"):
        threats.append(
            {
                "id": item["id"],
                "name": item["name"],
                "created": timestamp(item["created"]),
                "updated": timestamp(item["updated"]),
                "summary": item.get("summary"),
                "severity": item.get("severity"),
                "investigation": item.get("investigation"),
                "response": item.get("response"),
                "mitigation": item.get("mitigation"),
                "industries": item.get("industries") or [],
                "geographies": item.get("geographies") or [],
                "threat_types": item.get("threat_types") or [],
                "threat_actors": item.get("threat_actors") or [],
                "techniques": item.get("techniques") or [],
                "high_order_sigma_rules": [
                    hos[i]
                    for i in item.get("related_high_order_sigma_rules") or []
                    if i in hos or warn(f"Active Threat {item['id']} references missing HoS {i}")
                ],
                # The behavior rules of the threat and the stage rules of its
                # HoS rules.
                "rules": [
                    {"uid": uid, "name": by_uid[uid]["name"]}
                    for uid in dict.fromkeys(
                        [
                            rules[i]["uid"]
                            for i in item.get("related_behavioral_rules") or []
                            if i in rules
                            or warn(f"Active Threat {item['id']} references missing rule {i}")
                        ]
                        + [
                            uid
                            for i in item.get("related_high_order_sigma_rules") or []
                            for uid in hos_rules.get(i, [])
                        ]
                    )
                ],
            }
        )
    out = [
        "// Generated by scripts/vendor.py from the SOC Prime DetectFlow detection",
        f"// content snapshot {version}. Do not edit by hand.",
        "",
        f'let $version = "{version}"',
        "",
        "// The SOC Prime Sigma rules, keyed by Sigma rule ID.",
        "let $rules = {",
    ]
    for rule in sorted(rules.values(), key=lambda r: r["uid"]):
        out.append(f"  // {rule['name']}")
        out.append(f'  "{rule["uid"]}": r#"{rule["body"]}"#,')
    out += [
        "}",
        "",
        "// The SOC Prime Active Threats. Rule references are Sigma rule IDs.",
        f"let $active_threats = {tql(sorted(threats, key=lambda t: t['id']))}",
        "",
    ]
    (PACKAGE / "constants.tql").write_text("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
